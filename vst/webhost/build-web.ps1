# ============================================================================
#  Builds web/index.html: ONE self-contained file, from the plugin UI (vst/ui),
#  the factory presets and the web host (this folder). The same file is written
#  to docs/index.html, so GitHub Pages serves the web build from the repo.
#  Usage: powershell -ExecutionPolicy Bypass -File vst\webhost\build-web.ps1
# ============================================================================
$ErrorActionPreference = 'Stop'
$vst  = Split-Path $PSScriptRoot -Parent
$repo = Split-Path $vst -Parent
$ui   = Join-Path $vst 'ui'
$outs = @((Join-Path $repo 'web\index.html'), (Join-Path $repo 'docs\index.html'))
$utf8 = [Text.UTF8Encoding]::new($false)
$read = { param($path) [IO.File]::ReadAllText($path, $utf8) }

$html = & $read (Join-Path $ui 'index.html')
$version = (Select-String -Path (Join-Path $vst 'CMakeLists.txt') -Pattern 'project\(IWubYouVST VERSION ([0-9.]+)').Matches[0].Groups[1].Value

function Script([string]$code) {
    if ($code -match '</script') { throw 'inlined code must not contain </script' }
    return "<script>`n$code`n</script>"
}

# CSS
$css = & $read (Join-Path $ui 'css\style.css')
$link = '<link rel="stylesheet" href="css/style.css">'
if (-not $html.Contains($link)) { throw 'stylesheet link not found in ui/index.html' }
$html = $html.Replace($link, "<style>`n$css`n</style>")

# Factory presets + web host + DSP go in before the bridge (engine-juce.js) is constructed
$factoryJson = (& $read (Join-Path $vst 'presets\factory_presets.json')).Trim()
$hostScripts = @(
    (Script ("// factory presets (vst/presets/factory_presets.json)`nconst FACTORY_JSON = $factoryJson;")),
    (Script (& $read (Join-Path $PSScriptRoot 'factory.js'))),
    (Script (& $read (Join-Path $PSScriptRoot 'dsp-worklet.js'))),
    (Script (& $read (Join-Path $PSScriptRoot 'web-host.js')))
) -join "`n"

# Inline every <script src="js/..."></script> in order
$html = [regex]::Replace($html, '<script src="js/([\w.-]+)"></script>', {
    param($m)
    $name = $m.Groups[1].Value
    $code = Script (& $read (Join-Path $ui "js\$name"))
    if ($name -eq 'engine-juce.js') { return "$hostScripts`n$code" }
    return $code
})
if ($html -match 'src="js/') { throw 'a script was not inlined' }
if (-not $html.Contains('const FACTORY_JSON')) { throw 'engine-juce.js not found: web host not inserted' }

$banner = @"
<!--
  I Wub You v$version, web build. ONE self-contained file: UI, DSP and factory presets.
  GENERATED by vst/webhost/build-web.ps1 from vst/ui + vst/webhost: edit those, not this file.
  Open in Chrome or Edge (works straight from disk with the built-in test sources; start.bat serves it for the
  lower-latency AudioWorklet path and the microphone / tab / file inputs).
-->
"@
$html = $html.Replace('<!doctype html>', "<!doctype html>`n$banner")
$html = $html.Replace('<title>I Wub You</title>', "<title>I Wub You v$version</title>")

foreach ($out in $outs) {
    New-Item -ItemType Directory -Force (Split-Path $out -Parent) | Out-Null
    [IO.File]::WriteAllText($out, $html, $utf8)
    Write-Host ("Wrote {0} ({1:N0} KB)" -f $out, ((Get-Item $out).Length / 1KB))
}
